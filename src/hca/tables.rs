// Coefficient tables, as exact `f32` bit patterns

const fn f32s<const N: usize>(bits: [u32; N]) -> [f32; N] {
	let mut out = [0.0f32; N];
	let mut i = 0;
	while i < N {
		out[i] = f32::from_bits(bits[i]);
		i += 1;
	}
	out
}

